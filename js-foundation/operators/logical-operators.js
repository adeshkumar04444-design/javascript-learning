// Logical Operators: && (AND), || (OR), ! (NOT)

let isAdult = true;
let hasLicense = false;
console.log(isAdult && hasLicense); // false (AND operator, both conditions must be true)
console.log(isAdult || hasLicense); // true (OR operator, at least one condition must be true)
console.log(!isAdult); // false (NOT operator, negates the boolean value)
