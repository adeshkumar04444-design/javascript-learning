// Objects: A collection of key-value pairs where the keys are strings (or symbols) and the values can be of any data type, including other objects. Objects are used to store and organize data in a structured way.

let person = {
    firstName: "John",
    lastName: "Doe",
    age: 30
};

console.log(typeof person); // Output: "object"
console.log(person.firstName); // Output: "John"
console.log(person["lastName"]); // Output: "Doe"   