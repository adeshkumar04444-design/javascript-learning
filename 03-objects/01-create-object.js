/*
=====================================
Creating an Object in JavaScript
=====================================

An object is a collection of key-value pairs.
Each key is called a property, and every property stores a value.
*/

// Creating an object using object literal syntax
const person = {
  // Property: name
  name: "John",

  // Property: age
  age: 30,

  // Property: isEmployed
  isEmployed: true,
};

// printing the complete object
console.log(person);

/*
output:
{
  name: 'John',
  age: 30,
  isEmployed: true
}
*/
